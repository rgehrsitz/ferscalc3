// Package regression contains deterministic regression tests for ferscalc3
// using the TEST_SIMPLE_1.0 scenario format originally developed in the ferex project.
//
// These 9 scenarios (excluding CSRS scenario 08) cover:
//
//	01 - FERS age 62/20yrs:            standard 1.1% multiplier
//	02 - FERS MRA+10 age 57/10yrs:     MRA+10 early retirement reduction
//	03 - FERS age 60/20yrs + fed tax:  federal tax applied
//	04 - FERS SRS age 58/30yrs:        SRS paid until age 62
//	05 - SS claim age 67:              social security starts mid-projection
//	06 - Survivor 10% cost:            50% survivor election reduces pension by 10%
//	07 - State tax 5% + TSP:           TSP fixed withdrawal, multi-level taxes
//	09 - TSP fixed $12k/yr:            TSP-only notable income source
//	10 - Tax-free state + SRS stop:    SRS stops at 62, SS starts
//
// The expected CSVs are generated FROM ferscalc3 (not from ferex), making this a
// ferscalc3 stability test suite. Run with -update flag to regenerate expected CSVs:
//
//	go test ./test/regression/... -run TestUpdateExpectedCSVs -update
//
// Column definitions match ferex's TEST_SIMPLE_1.0 format:
//   - FERSAnnuity: pension + survivor pension (retiree's reduced pension amount)
//   - SRS: FERS Supplement
//   - SocialSecurity: SS benefit for PersonA
//   - TSPWithdrawal: TSP withdrawal for PersonA
//   - TaxFederal: federal income tax
//   - TaxState: state income tax
//   - NetAfterTax: FERSAnnuity + SRS + SS + TSP - TaxFederal - TaxState
//     (excludes FEHB and Medicare premiums, consistent with ferex's formula)
package regression_test

