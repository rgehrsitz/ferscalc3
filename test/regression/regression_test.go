func buildEmployee(t *testing.T, sc testScenario, retDate time.Time) *domain.Employee {
	t.Helper()

	birthDate := parseDate(t, sc.Person.BirthDate)

	// Derive hire date: retirement_date minus service_years (integer years, approximate).
	// For MRA+10 scenarios the service is exactly stated; we trust the YAML value.
	hireDate := retDate.AddDate(-int(sc.Person.ServiceYears), 0, 0)

	// SS benefits in scenario are annual; ferscalc3 stores monthly
	ssAt62Monthly := decimal.NewFromFloat(sc.Social.SSAge62Estimate / 12.0)
	ssAtFRAMonthly := decimal.NewFromFloat(sc.Social.Primary / 12.0)

	return &domain.Employee{
		Name:                           "PersonA",
		BirthDate:                      birthDate,
		HireDate:                       hireDate,
		EmploymentType:                 domain.EmploymentTypeFederal,
		High3Salary:                    decimal.NewFromFloat(sc.Person.High3),
		SSBenefit62:                    ssAt62Monthly,
		SSBenefitFRA:                   ssAtFRAMonthly,
		SurvivorBenefitElectionPercent: decimal.NewFromFloat(sc.Person.SurvivorPct),
		// TSP: set an initial balance only if the scenario uses TSP withdrawals;
		// use a large enough balance so it doesn't deplete during the projection.
		TSPBalanceTraditional: tspBalanceForScenario(sc),
		TSPBalanceRoth:        decimal.Zero,
	}
}

// buildDummyEmployee creates a non-federal placeholder for PersonB.
// ferscalc3 requires two persons; PersonB contributes nothing to the calculation.
func buildDummyEmployee() *domain.Employee {
	return &domain.Employee{
		Name:           "PersonB",
		BirthDate:      time.Date(1970, 1, 1, 0, 0, 0, 0, time.UTC),
		HireDate:       time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC),
		EmploymentType: domain.EmploymentTypeNonFederal,
	}
}

func buildScenario(t *testing.T, sc testScenario, personA *domain.Employee, retDate time.Time) *domain.Scenario {
	t.Helper()

	strategy := "none"
	var targetMonthly *decimal.Decimal
	if sc.TSP.WithdrawalFixed > 0 {
		strategy = "need_based"
		v := decimal.NewFromFloat(sc.TSP.WithdrawalFixed / 12.0)
		targetMonthly = &v
	}

	// PersonB retires at same date but has no income; set far-future retirement
	// so she is never "retired" in the projection (non-federal, no pension).
	personBRetDate := retDate.AddDate(40, 0, 0)

	return &domain.Scenario{
		Name: "regression",
		PersonA: domain.RetirementScenario{
			EmployeeName:               "PersonA",
			RetirementDate:             retDate,
			SSStartAge:                 sc.Social.ClaimAge,
			TSPWithdrawalStrategy:      strategy,
			TSPWithdrawalTargetMonthly: targetMonthly,
		},
		PersonB: domain.RetirementScenario{
			EmployeeName:          "PersonB",
			RetirementDate:        personBRetDate,
			SSStartAge:            70,
			TSPWithdrawalStrategy: "none",
		},
	}
}

func buildAssumptions(t *testing.T, sc testScenario) domain.GlobalAssumptions {
	t.Helper()

	// TEST_SIMPLE_1.0 uses zero COLA, zero inflation, zero TSP growth.
	// This makes projections fully deterministic.
	baseYear := sc.Ruleset.Year
	if baseYear == 0 {
		baseYear = 2025
	}
	// projectionBaseYear is one year before retirement so that projection[1]
	// corresponds to the first full year of retirement (matching the CSV rows).
	retYear, _ := strconv.Atoi(sc.Person.RetirementDate[:4])
	projBaseYear := retYear - 1
	if projBaseYear < baseYear {
		projBaseYear = baseYear
	}

	return domain.GlobalAssumptions{
		InflationRate:               decimal.Zero, // deterministic: no inflation
		FEHBPremiumInflation:        decimal.Zero,
		TSPReturnPreRetirement:      decimal.Zero,
		TSPReturnPostRetirement:     decimal.Zero,
		COLAGeneralRate:             decimal.Zero, // no COLA in TEST_SIMPLE_1.0
		FederalBracketInflationRate: decimal.Zero,
		// projBaseYear is one year before retirement; add 1 so the projection
		// covers the full CSV range (projBaseYear, retirementYear, ..., retirementYear+years-1).
		ProjectionYears:    sc.Simulation.Years + 1,
		ProjectionBaseYear: projBaseYear,
		CurrentLocation: domain.Location{
			State: "Pennsylvania",
		},
		FederalRules: defaultFederalRules(),
	}
}

func defaultFederalRules() domain.FederalRules {
	return domain.FederalRules{
		FERSRules: domain.FERSRules{
			SRSEarningsLimit: decimal.NewFromInt(23400),
		},
		FederalTaxConfig: domain.FederalTaxConfig{
			StandardDeductionMFJ:        decimal.NewFromInt(30000),
			StandardDeductionSingle:     decimal.NewFromInt(15000),
			AdditionalStandardDeduction: decimal.NewFromInt(1600),
		},
		StateLocalTaxConfig: domain.StateLocalTaxConfig{
			PennsylvaniaRate: decimal.NewFromFloat(0.0307),
		},
		MedicareConfig: domain.MedicareConfig{
			// BasePremium2025 = 0 signals "no Medicare" in the regression harness.
			// Note: NewMedicareCalculatorWithConfig treats zero as "use default",
			// so the harness excludes Medicare from NetAfterTax by using the
			// explicit gross - tax formula rather than proj.NetIncome.
			BasePremium2025:      decimal.Zero,
			PremiumInflationRate: decimal.Zero,
		},
	}
}

// tspBalanceForScenario sets a large enough TSP balance if the scenario has TSP withdrawals.
func tspBalanceForScenario(sc testScenario) decimal.Decimal {
	if sc.TSP.WithdrawalFixed <= 0 {
		return decimal.Zero
	}
	// Provide 50× the annual withdrawal as initial balance to prevent depletion
	return decimal.NewFromFloat(sc.TSP.WithdrawalFixed * 50)
}

