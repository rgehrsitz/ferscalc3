// TestRegressionSuite validates that ferscalc3's outputs match the expected CSVs.
// The expected CSVs are generated by ferscalc3 itself (see TestUpdateExpectedCSVs).
func TestRegressionSuite(t *testing.T) {
	scenarios, err := filepath.Glob("scenarios/*.yaml")
	require.NoError(t, err)
	require.NotEmpty(t, scenarios, "no scenario YAML files found in scenarios/")

	for _, scenarioFile := range scenarios {
		scenarioFile := scenarioFile
		name := strings.TrimSuffix(filepath.Base(scenarioFile), ".yaml")
		t.Run(name, func(t *testing.T) {
			runRegressionScenario(t, scenarioFile)
		})
	}
}

// TestUpdateExpectedCSVs regenerates the expected CSV files from ferscalc3's current output.
// Run this when the calculation engine is intentionally changed:
//
//	go test ./test/regression/... -run TestUpdateExpectedCSVs -update
func TestUpdateExpectedCSVs(t *testing.T) {
	if !*updateExpected {
		t.Skip("run with -update to regenerate expected CSV files")
	}

	scenarios, err := filepath.Glob("scenarios/*.yaml")
	require.NoError(t, err)
	require.NotEmpty(t, scenarios)

	require.NoError(t, os.MkdirAll("expected", 0o755))

	for _, scenarioFile := range scenarios {
		name := strings.TrimSuffix(filepath.Base(scenarioFile), ".yaml")
		t.Run(name, func(t *testing.T) {
			generateExpectedCSV(t, scenarioFile)
		})
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// Core Runner
// ─────────────────────────────────────────────────────────────────────────────

func runRegressionScenario(t *testing.T, scenarioFile string) {
	t.Helper()

	sc, projection, projectionStartYear := runProjection(t, scenarioFile)

	// Load expected CSV
	baseName := strings.TrimSuffix(filepath.Base(scenarioFile), ".yaml")
	expectedFile := filepath.Join("expected", baseName+".csv")
	expected, err := loadExpectedCSV(t, expectedFile)
	require.NoError(t, err, "reading expected CSV %s", expectedFile)
	require.NotEmpty(t, expected, "expected CSV must have at least one data row")

	// Verify that all expected CSV years fall within the projection bounds.
	for _, row := range expected {
		idx := row.Year - projectionStartYear
		require.GreaterOrEqual(t, idx, 0,
			"CSV year %d is before projectionStartYear %d", row.Year, projectionStartYear)
		require.Less(t, idx, len(projection),
			"CSV year %d maps to projection index %d which is out of bounds (len=%d)",
			row.Year, idx, len(projection))
	}

	// Tolerance: all columns use ±$1 (covering floating-point rounding).
	// Tax columns get ±$2 because ferscalc3 uses bracket-based progressive tax
	// while the original ferex scenarios used flat rates — the expected CSVs
	// are now ferscalc3-native, so the tolerance only covers rounding noise.
	_ = sc // sc used in generateExpectedCSV; suppress "declared but not used"

	for _, row := range expected {
		proj := projection[row.Year-projectionStartYear]
		t.Run(fmt.Sprintf("year_%d", row.Year), func(t *testing.T) {
			// FERS Annuity (pension + any survivor pension, but NOT SRS, NOT SS)
			totalPension := proj.PensionPersonA.Add(proj.SurvivorPensionPersonA).InexactFloat64()
			assert.InDelta(t, row.FERSAnnuity, totalPension, 1.0,
				"FERSAnnuity mismatch in year %d", row.Year)

			// FERS Supplement (SRS)
			assert.InDelta(t, row.SRS, proj.FERSSupplementPersonA.InexactFloat64(), 1.0,
				"SRS mismatch in year %d", row.Year)

			// Social Security
			assert.InDelta(t, row.SocialSec, proj.SSBenefitPersonA.InexactFloat64(), 1.0,
				"SocialSecurity mismatch in year %d", row.Year)

			// TSP Withdrawal
			assert.InDelta(t, row.TSPWithdraw, proj.TSPWithdrawalPersonA.InexactFloat64(), 1.0,
				"TSPWithdrawal mismatch in year %d", row.Year)

			// Federal Tax
			assert.InDelta(t, row.TaxFederal, proj.FederalTax.InexactFloat64(), 1.0,
				"TaxFederal mismatch in year %d", row.Year)

			// State Tax
			assert.InDelta(t, row.TaxState, proj.StateTax.InexactFloat64(), 1.0,
				"TaxState mismatch in year %d", row.Year)

			// Net After Tax: gross - fed tax - state tax (excludes FEHB/Medicare)
			// This matches ferex's NetAfterTax formula:
			//   NetAfterTax = pension + SRS + SS + TSP - fedTax - stateTax
			gross := proj.PensionPersonA.Add(proj.SurvivorPensionPersonA).
				Add(proj.FERSSupplementPersonA).
				Add(proj.SSBenefitPersonA).
				Add(proj.TSPWithdrawalPersonA)
			net := gross.Sub(proj.FederalTax).Sub(proj.StateTax).InexactFloat64()
			assert.InDelta(t, row.NetAfterTax, net, 1.0,
				"NetAfterTax mismatch in year %d", row.Year)
		})
	}
}

// generateExpectedCSV runs ferscalc3 for a scenario and writes the output to
// the expected/ directory. Called by TestUpdateExpectedCSVs.
func generateExpectedCSV(t *testing.T, scenarioFile string) {
	t.Helper()

	_, projection, projectionStartYear := runProjection(t, scenarioFile)

	baseName := strings.TrimSuffix(filepath.Base(scenarioFile), ".yaml")
	outFile := filepath.Join("expected", baseName+".csv")

	f, err := os.Create(outFile)
	require.NoError(t, err, "creating output CSV %s", outFile)
	defer f.Close()

	w := csv.NewWriter(f)
	defer w.Flush()

	require.NoError(t, w.Write([]string{
		"Year", "FERSAnnuity", "SRS", "SocialSecurity",
		"TSPWithdrawal", "TaxFederal", "TaxState", "NetAfterTax",
	}))

	// Write one row per projection year, starting from the retirement year.
	// Skip the pre-retirement year at index 0 (projectionStartYear).
	for i, proj := range projection {
		calYear := projectionStartYear + i
		if i == 0 {
			// Skip the pre-retirement offset year
			continue
		}
		pension := proj.PensionPersonA.Add(proj.SurvivorPensionPersonA)
		srs := proj.FERSSupplementPersonA
		ss := proj.SSBenefitPersonA
		tsp := proj.TSPWithdrawalPersonA
		fedTax := proj.FederalTax
		stateTax := proj.StateTax
		gross := pension.Add(srs).Add(ss).Add(tsp)
		net := gross.Sub(fedTax).Sub(stateTax)

		require.NoError(t, w.Write([]string{
			strconv.Itoa(calYear),
			roundCents(pension),
			roundCents(srs),
			roundCents(ss),
			roundCents(tsp),
			roundCents(fedTax),
			roundCents(stateTax),
			roundCents(net),
		}))
	}

	t.Logf("wrote %s", outFile)
}

// roundCents formats a Decimal as a string rounded to 2 decimal places.
func roundCents(d decimal.Decimal) string {
	f := d.InexactFloat64()
	rounded := math.Round(f*100) / 100
	return strconv.FormatFloat(rounded, 'f', 2, 64)
}

