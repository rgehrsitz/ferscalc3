// runProjection loads a scenario YAML, builds ferscalc3 domain objects, runs the
// projection engine, and returns the parsed scenario, the projection slice, and
// projectionStartYear so callers can map CSV year → slice index.
func runProjection(t *testing.T, scenarioFile string) (testScenario, []domain.AnnualCashFlow, int) {
	t.Helper()

	raw, err := os.ReadFile(scenarioFile)
	require.NoError(t, err, "reading scenario file %s", scenarioFile)

	var sc testScenario
	require.NoError(t, yaml.Unmarshal(raw, &sc), "parsing scenario YAML %s", scenarioFile)

	retDate := parseDate(t, sc.Person.RetirementDate)
	personA := buildEmployee(t, sc, retDate)
	personB := buildDummyEmployee()

	scenario := buildScenario(t, sc, personA, retDate)
	assumptions := buildAssumptions(t, sc)

	engine := calculation.NewCalculationEngineWithConfig(assumptions)
	projection := engine.GenerateAnnualProjection(personA, personB, scenario, &assumptions, assumptions.FederalRules)

	// projectionStartYear is one year before the retirement year.
	// projection[0] corresponds to projectionStartYear (pre-retirement).
	// projection[1] corresponds to the retirement year.
	retYear := retDate.Year()
	projectionStartYear := retYear - 1
	if projectionStartYear < sc.Ruleset.Year {
		projectionStartYear = sc.Ruleset.Year
	}

	return sc, projection, projectionStartYear
}

