func loadExpectedCSV(t *testing.T, path string) ([]expectedRow, error) {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	r := csv.NewReader(f)
	records, err := r.ReadAll()
	if err != nil {
		return nil, err
	}

	// Skip header row
	var rows []expectedRow
	for _, rec := range records[1:] {
		if len(rec) < 8 {
			continue
		}
		row := expectedRow{
			Year:        parseInt(t, rec[0]),
			FERSAnnuity: parseFloat(t, rec[1]),
			SRS:         parseFloat(t, rec[2]),
			SocialSec:   parseFloat(t, rec[3]),
			TSPWithdraw: parseFloat(t, rec[4]),
			TaxFederal:  parseFloat(t, rec[5]),
			TaxState:    parseFloat(t, rec[6]),
			NetAfterTax: parseFloat(t, rec[7]),
		}
		rows = append(rows, row)
	}
	return rows, nil
}

func parseInt(t *testing.T, s string) int {
	t.Helper()
	v, err := strconv.Atoi(strings.TrimSpace(s))
	require.NoError(t, err, "parseInt(%q)", s)
	return v
}

func parseFloat(t *testing.T, s string) float64 {
	t.Helper()
	v, err := strconv.ParseFloat(strings.TrimSpace(s), 64)
	require.NoError(t, err, "parseFloat(%q)", s)
	return v
}

func parseDate(t *testing.T, s string) time.Time {
	t.Helper()
	d, err := time.Parse("2006-01-02", s)
	require.NoError(t, err, "parseDate(%q)", s)
	return d
}
