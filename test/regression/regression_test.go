// updateExpected is set by -update flag to regenerate expected CSVs.
var updateExpected = flag.Bool("update", false, "regenerate expected CSV files from current ferscalc3 output")

// ─────────────────────────────────────────────────────────────────────────────
// TEST_SIMPLE_1.0 Schema
// ─────────────────────────────────────────────────────────────────────────────

// testScenario represents the TEST_SIMPLE_1.0 YAML input format.
type testScenario struct {
	Ruleset struct {
		Year   int    `yaml:"year"`
		Source string `yaml:"source"`
	} `yaml:"ruleset"`
	Person struct {
		BirthDate      string  `yaml:"birth_date"`
		RetirementDate string  `yaml:"retirement_date"`
		High3          float64 `yaml:"high3"`
		ServiceYears   float64 `yaml:"service_years"`
		FERS           bool    `yaml:"fers"`
		MRA10          bool    `yaml:"mra10"` // if true, uses MRA+10 (under-20-yr) retirement
		SurvivorPct    float64 `yaml:"survivor_pct"`
	} `yaml:"person"`
	TSP struct {
		WithdrawalFixed float64 `yaml:"withdrawal_fixed"` // annual fixed withdrawal
	} `yaml:"tsp"`
	Taxes struct {
		FlatFederalRate float64 `yaml:"flat_federal_rate"`
		FlatStateRate   float64 `yaml:"flat_state_rate"`
	} `yaml:"taxes"`
	Social struct {
		ClaimAge        int     `yaml:"claim_age"`
		Primary         float64 `yaml:"primary"`           // annual SS benefit at FRA
		SSAge62Estimate float64 `yaml:"ss_age62_estimate"` // annual SS benefit at 62
	} `yaml:"social"`
	Simulation struct {
		Years int `yaml:"years"`
		Runs  int `yaml:"runs"`
	} `yaml:"simulation"`
}

// expectedRow holds one year's expected output from the CSV.
// NetAfterTax = FERSAnnuity + SRS + SocialSec + TSPWithdraw - TaxFederal - TaxState
// (excludes FEHB and Medicare to remain consistent with ferex's TEST_SIMPLE_1.0 formula).
type expectedRow struct {
	Year        int
	FERSAnnuity float64
	SRS         float64
	SocialSec   float64
	TSPWithdraw float64
	TaxFederal  float64
	TaxState    float64
	NetAfterTax float64
}

